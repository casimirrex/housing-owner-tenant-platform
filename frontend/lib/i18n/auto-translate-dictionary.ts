/**
 * Look up a candidate text node value. Returns undefined if it's not in the
 * dictionary (i.e. it's user-generated content or just not translated yet).
 */
export function lookupTranslation(
  text: string,
  locale: SupportedLocale
): string | undefined {
  if (locale === "en") return undefined;
  const trimmed = text.trim();
  if (!trimmed) return undefined;
  const entry = AUTO_TRANSLATE_MAP[trimmed];
  if (!entry) return undefined;
  const t = entry[locale as Exclude<SupportedLocale, "en">];
  if (!t) return undefined;
  // Preserve leading/trailing whitespace so we don't squish spacing/wrapping.
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  return leading + t + trailing;
}
